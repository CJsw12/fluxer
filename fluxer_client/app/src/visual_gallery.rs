struct GalleryHost {
    client: Entity<ClientView>,
    title: SharedString,
    _driver: Task<()>,
}

impl Render for GalleryHost {
    fn render(&mut self, _window: &mut Window, cx: &mut Context<Self>) -> impl IntoElement {
        let app_theme = Theme::current(cx);
        div()
            .size_full()
            .flex()
            .flex_col()
            .bg(app_theme.background)
            .child(crate::ui::titlebar::render(self.title.clone(), &app_theme))
            .child(div().flex_1().min_h_0().w_full().child(self.client.clone()))
    }
}

fn find_capture_script() -> Option<PathBuf> {
    let direct = PathBuf::from("scripts/visual_parity_diff.py");
    if direct.is_file() {
        return Some(direct);
    }
    if let Ok(exe) = std::env::current_exe() {
        for ancestor in exe.ancestors().take(6) {
            let candidate = ancestor.join("scripts").join("visual_parity_diff.py");
            if candidate.is_file() {
                return Some(candidate);
            }
        }
    }
    None
}

async fn capture_window_png(script: PathBuf, pid: u32, out_png: PathBuf) -> Result<()> {
    let status = tokio::process::Command::new("python")
        .arg("-I")
        .arg(&script)
        .arg("--capture-pid")
        .arg(pid.to_string())
        .arg("--out")
        .arg(&out_png)
        .status()
        .await
        .with_context(|| format!("spawn capture script {}", script.display()))?;
    if !status.success() {
        anyhow::bail!("capture script exited with {status} for {}", out_png.display());
    }
    Ok(())
}

/// Runs the offline 12-scenario visual gallery in a real GPUI window and saves
/// all 12 PNG screenshots + `manifest.json` into `out_dir`.
pub fn run_visual_gallery(out_dir: &Path) -> Result<()> {
    crate::platform::set_os_integration_enabled(false);
    std::fs::create_dir_all(out_dir)
        .with_context(|| format!("create visual gallery dir {}", out_dir.display()))?;

    let rt = tokio::runtime::Builder::new_multi_thread()
        .worker_threads(2)
        .enable_all()
        .build()
        .context("visual gallery tokio runtime")?;
    let handle = rt.handle().clone();
    let media_base = start_offline_media_server(&handle);
    let images = crate::http::ImageHttpClient::new(handle.clone(), true).context("image http client")?;
    let initial_theme = std::env::var("FLUXER_THEME")
        .ok()
        .and_then(|v| ThemeKind::parse(&v))
        .unwrap_or(ThemeKind::Dark);
    let capture_script = find_capture_script();
    let out_dir = out_dir.to_path_buf();
    let pid = std::process::id();

    let run_error: std::rc::Rc<std::cell::RefCell<Option<String>>> = std::rc::Rc::default();
    let run_error_slot = run_error.clone();
    let run_error_open = run_error.clone();

    gpui_kit::application().with_assets(crate::icons::AppAssets).run(move |cx: &mut App| {
        gpui_kit::init(cx);
        crate::shortcuts::bind_keys(cx);
        theme::set_kind(initial_theme, cx);
        cx.set_http_client(Arc::new(images));

        let bounds = Bounds::centered(None, size(px(1280.), px(800.)), cx);
        let options = WindowOptions {
            window_bounds: Some(WindowBounds::Windowed(bounds)),
            ..TitleBar::window_options()
        };
        let opened = gpui_kit::open_window(options, cx, |window, cx| {
            theme::apply(initial_theme, window, cx);
            let (backend, events) = build_gallery_backend(&handle, media_base.as_deref());
            let client = cx.new(|cx| ClientView::new(backend, events, window, cx));
            let client_for_task = client.clone();
            let media_for_task = media_base.clone();
            let out_for_task = out_dir.clone();
            let script_for_task = capture_script.clone();
            let rt_for_task = handle.clone();
            let err_for_task = run_error_slot.clone();

            cx.new(|cx| {
                let driver = cx.spawn_in(window, async move |this, cx| {
                    let mut manifest_entries = Vec::new();
                    for scenario in SCENARIOS {
                        let _ = this.update_in(cx, |host: &mut GalleryHost, window, cx| {
                            host.title = SharedString::from(format!(
                                "Fluxer Visual Gallery — {:02}/12 {}",
                                scenario.index, scenario.title
                            ));
                            window.resize(size(px(scenario.width), px(scenario.height)));
                            client_for_task.update(cx, |v, cx| {
                                apply_scenario(v, scenario.index, media_for_task.as_deref(), window, cx);
                            });
                            cx.notify();
                        });
                        // Give async loopback images and GPUI renderer time to paint cleanly.
                        cx.background_executor().timer(Duration::from_millis(450)).await;
                        let png_path = out_for_task.join(format!("{}.png", scenario.slug));
                        if let Some(script) = &script_for_task {
                            let script = script.clone();
                            let target = png_path.clone();
                            let cap = rt_for_task.spawn(capture_window_png(script, pid, target));
                            if let Ok(Err(err)) = cap.await {
                                *err_for_task.borrow_mut() = Some(format!("{err:#}"));
                                break;
                            }
                        }
                        manifest_entries.push(json!({
                            "index": scenario.index,
                            "slug": scenario.slug,
                            "title": scenario.title,
                            "width": scenario.width,
                            "height": scenario.height,
                            "file": format!("{}.png", scenario.slug),
                        }));
                    }
                    let manifest = json!({
                        "scenarios": manifest_entries,
                        "theme": initial_theme.as_str(),
                    });
                    if let Ok(text) = serde_json::to_string_pretty(&manifest) {
                        let _ = std::fs::write(out_for_task.join("manifest.json"), text);
                    }
                    let _ = cx.update(|_, cx| cx.quit());
                });
                GalleryHost {
                    client,
                    title: SharedString::new_static("Fluxer Visual Gallery"),
                    _driver: driver,
                }
            })
        });
        if let Err(err) = opened {
            *run_error_open.borrow_mut() = Some(format!("{err:#}"));
            cx.quit();
        }
    });

    if let Some(err) = run_error.borrow_mut().take() {
        anyhow::bail!(err);
    }
    Ok(())
}

