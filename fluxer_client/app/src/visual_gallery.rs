/// Starts an offline loopback HTTP server serving deterministic PNG/GIF assets.
fn start_offline_media_server(rt: &Handle) -> Option<String> {
    rt.block_on(async {
        let listener = TcpListener::bind("127.0.0.1:0").await.ok()?;
        let addr = listener.local_addr().ok()?;
        tokio::spawn(async move {
            while let Ok((mut stream, _)) = listener.accept().await {
                tokio::spawn(async move {
                    let mut buf = [0u8; 2048];
                    let n = stream.read(&mut buf).await.unwrap_or(0);
                    let req = std::str::from_utf8(&buf[..n]).unwrap_or("");
                    let path = req
                        .lines()
                        .next()
                        .and_then(|line| line.split_whitespace().nth(1))
                        .unwrap_or("/");
                    let (ct, body): (&str, &[u8]) = if path.contains(".gif") || path.contains("animated=true") {
                        ("image/gif", SAMPLE_ANIMATED_GIF)
                    } else if path.contains("/201/") || path.contains("photo1") {
                        ("image/png", AVATAR_1_PNG)
                    } else if path.contains("/202/") || path.contains("photo2") {
                        ("image/png", AVATAR_2_PNG)
                    } else if path.contains("/203/") || path.contains("yt") {
                        ("image/png", AVATAR_3_PNG)
                    } else if path.contains("/100/") {
                        ("image/png", AVATAR_4_PNG)
                    } else if path.contains("card") {
                        ("image/png", AVATAR_5_PNG)
                    } else {
                        ("image/png", AVATAR_0_PNG)
                    };
                    let header = format!(
                        "HTTP/1.1 200 OK\r\nContent-Type: {ct}\r\nContent-Length: {}\r\nConnection: close\r\n\r\n",
                        body.len()
                    );
                    let _ = stream.write_all(header.as_bytes()).await;
                    let _ = stream.write_all(body).await;
                });
            }
        });
        Some(format!("http://127.0.0.1:{}", addr.port()))
    })
}

fn synthetic_video_frame() -> DecodedVideoFrame {
    let (w, h) = (320u32, 180u32);
    let mut data = Vec::with_capacity((w * h * 4) as usize);
    for y in 0..h {
        for x in 0..w {
            let r = ((x * 160) / w + 32) as u8;
            let g = ((y * 140) / h + 40) as u8;
            let b = 210u8;
            data.extend_from_slice(&[r, g, b, 255]);
        }
    }
    DecodedVideoFrame {
        width: w,
        height: h,
        timestamp_us: 1_000,
        codec: Some(VideoCodec::H264),
        data,
    }
}

