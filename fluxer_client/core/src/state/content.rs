//! Message content parts: attachments, embeds, stickers, reactions and the
//! reply reference (`MessageResponseSchemas.ts`, `EmbedSchemas.ts`).

use serde::{Deserialize, Serialize};

use super::ids::Snowflake;
use super::model::null_default;

/// `MessageAttachmentFlags.IS_SPOILER` (`ChannelConstants.ts:134-138`).
pub const ATTACHMENT_FLAG_SPOILER: u32 = 1 << 3;
/// `MessageAttachmentFlags.CONTAINS_EXPLICIT_MEDIA`.
pub const ATTACHMENT_FLAG_EXPLICIT: u32 = 1 << 4;
/// `MessageAttachmentFlags.IS_ANIMATED`.
pub const ATTACHMENT_FLAG_ANIMATED: u32 = 1 << 5;

/// `MessageTypes.REPLY` (`ChannelConstants.ts:68`).
pub const MESSAGE_TYPE_REPLY: u8 = 19;

/// `MessageFlags` (`ChannelConstants.ts:116-123`).
pub mod message_flags {
    pub const CROSSPOSTED: u64 = 1 << 0;
    pub const IS_CROSSPOST: u64 = 1 << 1;
    pub const SUPPRESS_EMBEDS: u64 = 1 << 2;
    pub const SOURCE_MESSAGE_DELETED: u64 = 1 << 3;
    pub const SUPPRESS_NOTIFICATIONS: u64 = 1 << 12;
    pub const VOICE_MESSAGE: u64 = 1 << 13;
}

/// `MessageAttachmentResponse`.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Attachment {
    pub id: Snowflake,
    #[serde(default, deserialize_with = "null_default")]
    pub filename: String,
    #[serde(default)]
    pub title: Option<String>,
    #[serde(default)]
    pub description: Option<String>,
    #[serde(default)]
    pub content_type: Option<String>,
    #[serde(default, deserialize_with = "null_default")]
    pub size: u64,
    #[serde(default)]
    pub url: Option<String>,
    #[serde(default)]
    pub proxy_url: Option<String>,
    #[serde(default)]
    pub width: Option<u32>,
    #[serde(default)]
    pub height: Option<u32>,
    #[serde(default)]
    pub placeholder: Option<String>,
    /// `MessageAttachmentFlags` bits, see [`ATTACHMENT_FLAG_SPOILER`].
    #[serde(default, deserialize_with = "null_default")]
    pub flags: u32,
    /// Audio/video length in seconds.
    #[serde(default)]
    pub duration: Option<u32>,
    /// ISO 8601 time the attachment URL stops working (`expires_at`).
    #[serde(default)]
    pub expires_at: Option<String>,
    /// The server already expired the attachment (`expired`).
    #[serde(default, deserialize_with = "null_default")]
    pub expired: bool,
}

impl Attachment {
    pub fn is_spoiler(&self) -> bool {
        self.flags & ATTACHMENT_FLAG_SPOILER != 0
    }
}

/// Old name of [`Attachment`].
pub type AttachmentSummary = Attachment;

