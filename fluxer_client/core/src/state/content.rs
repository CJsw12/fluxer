/// `MessageEmbedResponse`. `children` holds at most one nested embed
/// generated by unfurlers.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Embed {
    /// rich, image, video, gifv, article, link, ...
    #[serde(rename = "type", default)]
    pub kind: Option<String>,
    #[serde(default)]
    pub url: Option<String>,
    #[serde(default)]
    pub title: Option<String>,
    #[serde(default)]
    pub description: Option<String>,
    /// Sidebar colour as `0xRRGGBB`.
    #[serde(default)]
    pub color: Option<u32>,
    #[serde(default)]
    pub timestamp: Option<String>,
    #[serde(default)]
    pub author: Option<EmbedAuthor>,
    #[serde(default)]
    pub image: Option<EmbedMedia>,
    #[serde(default)]
    pub thumbnail: Option<EmbedMedia>,
    #[serde(default)]
    pub video: Option<EmbedMedia>,
    #[serde(default)]
    pub audio: Option<EmbedMedia>,
    #[serde(default)]
    pub footer: Option<EmbedFooter>,
    #[serde(default, deserialize_with = "null_default")]
    pub fields: Vec<EmbedField>,
    #[serde(default)]
    pub provider: Option<EmbedProvider>,
    #[serde(default)]
    pub nsfw: Option<bool>,
    #[serde(default, deserialize_with = "null_default")]
    pub children: Vec<Embed>,
}

/// Old name of [`Embed`].
pub type EmbedSummary = Embed;

/// `MessageReferenceResponse`: reply (`kind` 0) or forward (`kind` 1).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct MessageReference {
    #[serde(default)]
    pub message_id: Option<Snowflake>,
    #[serde(default)]
    pub channel_id: Option<Snowflake>,
    #[serde(default)]
    pub guild_id: Option<Snowflake>,
    /// `MessageReferenceTypes`: 0 = DEFAULT (reply), 1 = FORWARD.
    #[serde(rename = "type", default, deserialize_with = "null_default")]
    pub kind: u8,
}

/// A reaction or custom-emoji reference: unicode (`id: None`, `name` is the
/// character) or custom (`id` + `name`). Equality is TS `sameEmoji`
/// (`id` and `name`; `animated` is ignored).
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PartialEmoji {
    #[serde(default)]
    pub id: Option<Snowflake>,
    #[serde(default, deserialize_with = "null_default")]
    pub name: String,
    #[serde(default, deserialize_with = "null_default")]
    pub animated: bool,
}

impl PartialEq for PartialEmoji {
    fn eq(&self, other: &Self) -> bool {
        self.id == other.id && self.name == other.name
    }
}

/// `MessageReactionResponse`. The server has no burst (super) reactions.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Reaction {
    pub emoji: PartialEmoji,
    #[serde(default, deserialize_with = "null_default")]
    pub count: u32,
    /// The current user reacted with this emoji.
    #[serde(default, deserialize_with = "null_default")]
    pub me: bool,
}

